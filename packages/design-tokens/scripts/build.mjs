// Builds every output of the design tokens (docs/ARCHITECTURE.md section 13):
//
//   dist/css/tokens.css                  both websites
//   dist/ts/tokens.ts                    both websites, where CSS is not enough
//   flutter/lib/feengo_design_tokens.dart  the app
//   flutter/pubspec.yaml, flutter/fonts/   the Dart package and its fonts
//
// The contrast check runs first; when it fails, nothing is written. Outputs are
// committed, and CI fails if a fresh build differs from them, so every output
// must be deterministic: no timestamps, no machine-specific paths.

import { copyFile, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { runContrastCheck } from './check-contrast.mjs';
import { cssFormat, dartFormat, tsFormat } from './formats.mjs';
import { PACKAGE_DIR, createStyleDictionary, resolvedTokens } from './tokens.mjs';

/**
 * The font files shipped: IBM Plex Sans Arabic, only the weights the S0 spec
 * uses (docs/design/s0/placeholder-home.md). Every weight in font.weight must
 * have a file here.
 */
export const FONT_FACES = [
  { file: 'IBMPlexSansArabic-Regular.ttf', weight: 400 },
  { file: 'IBMPlexSansArabic-Medium.ttf', weight: 500 },
  { file: 'IBMPlexSansArabic-Bold.ttf', weight: 700 },
];
const FONT_LICENSE = 'OFL.txt';

const FLUTTER_DIR = `${PACKAGE_DIR}flutter/`;

/** Folders that hold only generated files. The build empties them first. */
const GENERATED_DIRS = [`${PACKAGE_DIR}dist/`, `${FLUTTER_DIR}lib/`];

function pubspec(family) {
  return [
    '# Generated by packages/design-tokens/scripts/build.mjs. Do not edit.',
    'name: feengo_design_tokens',
    'description: FeenGo design tokens for Flutter, generated from packages/design-tokens.',
    'version: 0.1.0',
    'publish_to: none',
    '',
    'environment:',
    '  sdk: ^3.14.0',
    "  flutter: '>=3.50.0'",
    '',
    '# The Flutter SDK only (docs/ARCHITECTURE.md section 18.4).',
    'dependencies:',
    '  flutter:',
    '    sdk: flutter',
    '',
    'flutter:',
    '  fonts:',
    `    - family: ${family}`,
    '      fonts:',
    ...FONT_FACES.flatMap((f) => [
      `        - asset: fonts/${f.file}`,
      `          weight: ${f.weight}`,
    ]),
    '  # The font licence, so the app can show it on its licences page.',
    '  assets:',
    `    - fonts/${FONT_LICENSE}`,
    '',
  ].join('\n');
}

/** Copies the shipped fonts and their licence into the Flutter package, and nothing else. */
async function writeFlutterFonts() {
  const target = `${FLUTTER_DIR}fonts/`;
  await rm(target, { recursive: true, force: true });
  await mkdir(target, { recursive: true });
  for (const file of [...FONT_FACES.map((f) => f.file), FONT_LICENSE]) {
    await copyFile(`${PACKAGE_DIR}fonts/${file}`, target + file);
  }
}

/** Fails if fonts/ holds a file that is not shipped, or a weight has no file. */
async function checkFonts(allTokens) {
  const shipped = new Set([...FONT_FACES.map((f) => f.file), FONT_LICENSE]);
  const present = await readdir(`${PACKAGE_DIR}fonts/`);
  const unknown = present.filter((f) => !shipped.has(f));
  const missing = [...shipped].filter((f) => !present.includes(f));
  if (unknown.length > 0 || missing.length > 0) {
    throw new Error(
      `fonts/ must hold exactly the files in FONT_FACES and ${FONT_LICENSE}. Unknown: ${unknown.join(', ') || 'none'}. Missing: ${missing.join(', ') || 'none'}.`,
    );
  }
  const weights = allTokens.filter((t) => t.path[0] === 'font' && t.$type === 'fontWeight');
  for (const token of weights) {
    if (!FONT_FACES.some((f) => f.weight === token.$value)) {
      throw new Error(
        `${token.path.join('.')} is ${token.$value}, but no font file has that weight.`,
      );
    }
  }
  const family = allTokens.find((t) => t.path.join('.') === 'font.family.base');
  return [family.$value].flat()[0];
}

async function build() {
  if (!(await runContrastCheck())) {
    console.error('Build stopped: nothing was written.');
    return false;
  }
  console.log('');

  const sd = createStyleDictionary({
    formats: { 'feengo/css': cssFormat, 'feengo/ts': tsFormat, 'feengo/dart': dartFormat },
    platforms: {
      css: {
        transforms: ['name/kebab'],
        buildPath: `${PACKAGE_DIR}dist/css/`,
        files: [{ destination: 'tokens.css', format: 'feengo/css' }],
      },
      ts: {
        transforms: ['name/kebab'],
        buildPath: `${PACKAGE_DIR}dist/ts/`,
        files: [{ destination: 'tokens.ts', format: 'feengo/ts' }],
      },
      dart: {
        transforms: ['name/kebab'],
        buildPath: `${FLUTTER_DIR}lib/`,
        files: [{ destination: 'feengo_design_tokens.dart', format: 'feengo/dart' }],
      },
    },
  });
  const family = await checkFonts(await resolvedTokens(sd, 'css'));
  // Start from empty output folders, so a file the build no longer writes is
  // deleted, and CI's stale-output check sees it go.
  for (const dir of GENERATED_DIRS) await rm(dir, { recursive: true, force: true });
  await sd.buildAllPlatforms();
  await writeFlutterFonts();
  await writeFile(`${FLUTTER_DIR}pubspec.yaml`, pubspec(family));
  console.log(`✔︎ ${FLUTTER_DIR}pubspec.yaml`);
  console.log(`✔︎ ${FLUTTER_DIR}fonts/`);
  return true;
}

if (import.meta.main) {
  try {
    process.exitCode = (await build()) ? 0 : 1;
  } catch (error) {
    console.error(`Build failed: ${error.message}`);
    process.exitCode = 1;
  }
}
