const DART_WIDTH = 80;

/** `///` doc comment lines, wrapped to the Dart line width. */
function dartDoc(text, indent) {
  if (!text) return [];
  const sentence = /[.!?]$/.test(text) ? text : `${text}.`;
  const prefix = `${indent}/// `;
  const lines = [];
  let line = '';
  for (const word of sentence.split(/\s+/)) {
    if (line && prefix.length + line.length + 1 + word.length > DART_WIDTH) {
      lines.push(prefix + line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  lines.push(prefix + line);
  return lines;
}

const dartColor = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const dartDouble = (value) => num(value);
/** Flutter names only the weights 100 to 900 in steps of 100. */
function dartWeight(weight) {
  if (!Number.isInteger(weight) || weight < 100 || weight > 900 || weight % 100 !== 0) {
    throw new Error(`Font weight ${weight} has no FontWeight constant in Flutter.`);
  }
  return `FontWeight.w${weight}`;
}

/** `static const <type> <name> = <value>;`, broken after `=` when too long. */
function dartConst(type, name, value) {
  const line = `  static const ${type} ${name} = ${value};`;
  if (line.length <= DART_WIDTH) return [line];
  return [`  static const ${type} ${name} =`, `      ${value};`];
}

function dartColorsClass(themes, roles, descriptions) {
  const lines = [
    '/// The colour roles of one theme. Map each role to a theme colour explicitly;',
    '/// never generate a colour scheme from a seed colour, which would replace',
    '/// these values.',
    'class FeenGoColors {',
    '  /// Creates a set of colour roles.',
    '  const FeenGoColors({',
    ...roles.map((role) => `    required this.${role},`),
    '  });',
  ];
  for (const name of Object.keys(themes)) {
    lines.push('');
    lines.push(
      ...dartDoc(
        name === 'dark'
          ? 'Dark theme. Temporary values until the design system is approved (docs/ARCHITECTURE.md section 13)'
          : `${pascal(name)} theme`,
        '  ',
      ),
    );
    lines.push(`  static const FeenGoColors ${name} = FeenGoColors(`);
    for (const role of roles) lines.push(`    ${role}: ${dartColor(themes[name][role])},`);
    lines.push('  );');
  }
  for (const role of roles) {
    lines.push('');
    lines.push(...dartDoc(descriptions[role], '  '));
    lines.push(`  final Color ${role};`);
  }
  lines.push('}');
  return lines;
}

function dartTypography(tokens) {
  const styles = new Map();
  for (const token of tokens) {
    const [, style, property, script] = token.path;
    if (!styles.has(style)) styles.set(style, {});
    const entry = styles.get(style);
    if (property === 'fontSize') entry.fontSize = px(token);
    else if (property === 'fontWeight') entry.fontWeight = token.$value;
    else if (property === 'lineHeight' && (script === 'en' || script === 'ar')) {
      entry[`lineHeight${pascal(script)}`] = px(token);
    } else throw new Error(`Unexpected typography token ${token.path.join('.')}.`);
  }
  const lines = [
    '/// A step of the type scale. Line heights differ by script, because Arabic',
    '/// needs more line height than Latin.',
    'class FeenGoTextStyle {',
    '  /// Creates a step of the type scale.',
    '  const FeenGoTextStyle({',
    '    required this.fontSize,',
    '    required this.fontWeight,',
    '    required this.lineHeightEn,',
    '    required this.lineHeightAr,',
    '  });',
    '',
    '  /// Font size in logical pixels, before the system text scale.',
    '  final double fontSize;',
    '',
    '  /// Font weight. Only the weights in [FeenGoFontWeight] are shipped.',
    '  final FontWeight fontWeight;',
    '',
    '  /// Line height in logical pixels for English and other Latin text.',
    '  final double lineHeightEn;',
    '',
    '  /// Line height in logical pixels for Arabic.',
    '  final double lineHeightAr;',
    '',
    '  /// A [TextStyle] in the FeenGo font with the line height for',
    "  /// [languageCode]: 'ar' for Arabic, anything else for English.",
    '  TextStyle toTextStyle(String languageCode) {',
    "    final lineHeight = languageCode == 'ar' ? lineHeightAr : lineHeightEn;",
    '    return TextStyle(',
    '      fontFamily: FeenGoFont.family,',
    '      package: FeenGoFont.package,',
    '      fontSize: fontSize,',
    '      fontWeight: fontWeight,',
    '      height: lineHeight / fontSize,',
    '      leadingDistribution: TextLeadingDistribution.even,',
    '    );',
    '  }',
    '}',
    '',
    '/// The type scale.',
    'abstract final class FeenGoTypeScale {',
  ];
  let first = true;
  for (const [name, s] of styles) {
    for (const key of ['fontSize', 'fontWeight', 'lineHeightEn', 'lineHeightAr']) {
      if (s[key] === undefined) throw new Error(`typography.${name} has no ${key}.`);
    }
    if (!first) lines.push('');
    first = false;
    lines.push(`  /// ${pascal(name)}.`);
    lines.push(`  static const FeenGoTextStyle ${name} = FeenGoTextStyle(`);
    lines.push(`    fontSize: ${dartDouble(s.fontSize)},`);
    lines.push(`    fontWeight: ${dartWeight(s.fontWeight)},`);
    lines.push(`    lineHeightEn: ${dartDouble(s.lineHeightEn)},`);
    lines.push(`    lineHeightAr: ${dartDouble(s.lineHeightAr)},`);
    lines.push('  );');
  }
  lines.push('}');
  return lines;
}

const DART_GROUP_DOCS = {
  spacing: 'Spacing in logical pixels, on a 4 px grid.',
  radius: 'Corner radius in logical pixels.',
  size: 'Fixed sizes in logical pixels.',
  stroke: 'Line widths in logical pixels.',
  motion: 'Durations and easing curves. Drop motion when reduce motion is on.',
};

function dartConstantsClass(group, tokens) {
  const lines = [
    ...dartDoc(DART_GROUP_DOCS[group], ''),
    `abstract final class FeenGo${pascal(group)} {`,
  ];
  tokens.forEach((token, index) => {
    // A blank line around documented constants, none between bare ones.
    if (index > 0 && (token.$description || tokens[index - 1].$description)) lines.push('');
    const name = camel(token.path.slice(1));
    lines.push(...dartDoc(token.$description, '  '));
    switch (token.$type) {
      case 'dimension':
        lines.push(...dartConst('double', name, dartDouble(px(token))));
        break;
      case 'duration':
        lines.push(...dartConst('Duration', name, `Duration(milliseconds: ${num(ms(token))})`));
        break;
      case 'cubicBezier':
        lines.push(...dartConst('Cubic', name, `Cubic(${token.$value.map(num).join(', ')})`));
        break;
      default:
        throw new Error(`No Dart output for $type ${token.$type} (${token.path.join('.')}).`);
    }
  });
  lines.push('}');
  return lines;
}

export function dartFormat({ dictionary }) {
  const { themes, roles, descriptions } = collectThemes(dictionary.allTokens);
  const groups = byGroup(exportedTokens(dictionary.allTokens));
  const font = groups.get('font') ?? [];
  const family = font.find((t) => t.$type === 'fontFamily');
  const weights = font.filter((t) => t.$type === 'fontWeight');
  if (!family) throw new Error('font.family.base is missing.');

  const sections = [
    [
      '// GENERATED FILE. DO NOT EDIT.',
      '//',
      '// FeenGo design tokens, generated by Style Dictionary from',
      '// packages/design-tokens/tokens. Change the token JSON, then run',
      `// \`${BUILD_COMMAND}\`.`,
      '',
      "import 'package:flutter/animation.dart';",
      "import 'package:flutter/painting.dart';",
    ],
    [
      '/// The FeenGo font, shipped in this package. It covers English and Arabic.',
      'abstract final class FeenGoFont {',
      "  /// The family name declared in this package's pubspec.yaml.",
      `  static const String family = '${[family.$value].flat()[0]}';`,
      '',
      '  /// The package that declares the font: the `package` argument of [TextStyle].',
      "  static const String package = 'feengo_design_tokens';",
      '}',
    ],
    [
      '/// The font weights shipped in this package.',
      'abstract final class FeenGoFontWeight {',
      ...weights.flatMap((t, i) => [
        ...(i > 0 ? [''] : []),
        `  /// ${pascal(t.path.at(-1))}, ${t.$value}.`,
        ...dartConst('FontWeight', t.path.at(-1), dartWeight(t.$value)),
      ]),
      '}',
    ],
    dartColorsClass(themes, roles, descriptions),
    dartTypography(groups.get('typography') ?? []),
  ];
  for (const [group, tokens] of groups) {
    if (group === 'font' || group === 'typography') continue;
    sections.push(dartConstantsClass(group, tokens));
  }
  return sections.map((s) => s.join('\n')).join('\n\n') + '\n';
}
