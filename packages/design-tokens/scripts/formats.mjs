// Style Dictionary formats for the three outputs (docs/ARCHITECTURE.md section 13).
// Each one returns the whole file as a string. No timestamps, and tokens are
// written in source order, so the same tokens always give the same bytes.

import {
  camel,
  collectThemes,
  cssFontFamily,
  exportedTokens,
  kebab,
  ms,
  num,
  pascal,
  px,
} from './tokens.mjs';

const BUILD_COMMAND = 'pnpm --filter @feengo/design-tokens build';
const ROOT_FONT_SIZE_PX = 16;

/** Groups the exported tokens by their first path segment, in source order. */
function byGroup(tokens) {
  const groups = new Map();
  for (const token of tokens) {
    const [group] = token.path;
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(token);
  }
  return groups;
}

// ---------------------------------------------------------------------------
// CSS: dist/css/tokens.css
// ---------------------------------------------------------------------------

function cssValue(token) {
  switch (token.$type) {
    case 'dimension':
      // Type sizes in rem, so they follow the browser's text size setting.
      return token.path[0] === 'typography'
        ? `${num(px(token) / ROOT_FONT_SIZE_PX)}rem`
        : `${num(px(token))}px`;
    case 'duration':
      return `${num(ms(token))}ms`;
    case 'cubicBezier':
      return `cubic-bezier(${token.$value.map(num).join(', ')})`;
    case 'fontFamily':
      return cssFontFamily(token.$value);
    case 'fontWeight':
      return String(token.$value);
    default:
      throw new Error(`No CSS output for $type ${token.$type} (${token.path.join('.')}).`);
  }
}

const cssName = (path) => `--${path.map(kebab).join('-')}`;

function cssBlock(selectors, declarations, indent = '') {
  const lines = [`${indent}${selectors.join(`,\n${indent}`)} {`];
  for (const [name, value] of declarations) lines.push(`${indent}  ${name}: ${value};`);
  lines.push(`${indent}}`);
  return lines.join('\n');
}

export function cssFormat({ dictionary }) {
  const { themes, roles } = collectThemes(dictionary.allTokens);
  const tokens = exportedTokens(dictionary.allTokens);
  const themeDeclarations = (name) => [
    ['color-scheme', name],
    ...roles.map((role) => [cssName(['color', role]), themes[name][role]]),
  ];

  // Per-script line heights: `--typography-body-line-height` follows the page's lang.
  const lineHeightAliases = (script) =>
    tokens
      .filter((t) => t.path[0] === 'typography' && t.path.at(-1) === 'en')
      .map((t) => {
        const base = t.path.slice(0, -1);
        return [cssName(base), `var(${cssName([...base, script])})`];
      });

  const blocks = [
    '/**',
    ' * FeenGo design tokens. Generated by Style Dictionary from packages/design-tokens/tokens.',
    ` * Do not edit: change the token JSON, then run \`${BUILD_COMMAND}\`.`,
    ' *',
    ' * Themes: data-theme="light" or "dark" on any element sets one; a page with no',
    ' * data-theme follows the system setting, light when the system has none.',
    ' * Sizes: type in rem (16 px = 1rem), everything else in px.',
    ' */',
    '',
    cssBlock(
      [':root'],
      [...tokens.map((t) => [cssName(t.path), cssValue(t)]), ...lineHeightAliases('en')],
    ),
    '',
    '/* Arabic needs more line height than Latin (docs/design/brief.md section 6). */',
    cssBlock([':root:lang(ar)'], lineHeightAliases('ar')),
  ];
  // The selectors never overlap, so the cascade does not depend on the order of
  // the blocks: <html data-theme="dark"> matches only the dark block. The media
  // block comes last because it shares :root:not([data-theme]) with light.
  blocks.push(
    '',
    '/* Light theme: the default when no data-theme is set, or data-theme="light". */',
    cssBlock([':root:not([data-theme])', "[data-theme='light']"], themeDeclarations('light')),
    '',
    '/* Dark theme. Temporary values until the design system is approved (docs/ARCHITECTURE.md section 13). */',
    cssBlock(["[data-theme='dark']"], themeDeclarations('dark')),
    '',
    '/* No data-theme: follow the system setting. */',
    '@media (prefers-color-scheme: dark) {',
    cssBlock([':root:not([data-theme])'], themeDeclarations('dark'), '  '),
    '}',
  );
  return blocks.join('\n') + '\n';
}

// ---------------------------------------------------------------------------
// TypeScript: dist/ts/tokens.ts
// ---------------------------------------------------------------------------

function tsLeaf(token) {
  switch (token.$type) {
    case 'dimension':
      return px(token);
    case 'duration':
      return ms(token);
    case 'cubicBezier':
      return token.$value;
    case 'fontFamily':
      return cssFontFamily(token.$value);
    case 'fontWeight':
      return token.$value;
    default:
      throw new Error(`No TypeScript output for $type ${token.$type} (${token.path.join('.')}).`);
  }
}

function tsLiteral(value, indent) {
  if (typeof value === 'number') return num(value);
  if (typeof value === 'string') {
    const quote = value.includes("'") && !value.includes('"') ? '"' : "'";
    return quote + value.replace(/\\/g, '\\\\').replaceAll(quote, `\\${quote}`) + quote;
  }
  if (Array.isArray(value)) return `[${value.map((v) => tsLiteral(v, indent)).join(', ')}]`;
  const inner = `${indent}  `;
  const entries = Object.entries(value).map(([k, v]) => `${inner}${k}: ${tsLiteral(v, inner)},`);
  return `{\n${entries.join('\n')}\n${indent}}`;
}

const TS_GROUP_DOCS = {
  font: 'Font family (a CSS font-family list) and the weights shipped in fonts/.',
  typography:
    'Type scale in px. Line heights per script: `en` for English and Latin, `ar` for Arabic.',
  spacing: 'Spacing in px, on a 4 px grid.',
  radius: 'Corner radius in px.',
  size: 'Fixed sizes in px.',
  stroke: 'Line widths in px.',
  motion:
    'Durations in ms; easings as cubic-bezier control points. Drop motion when reduce motion is on.',
};

export function tsFormat({ dictionary }) {
  const { themes, roles, descriptions } = collectThemes(dictionary.allTokens);
  const themeNames = Object.keys(themes);
  const lines = [
    '/**',
    ' * FeenGo design tokens. Generated by Style Dictionary from packages/design-tokens/tokens.',
    ` * Do not edit: change the token JSON, then run \`${BUILD_COMMAND}\`.`,
    ' */',
    '',
    '/** The colour themes. The websites follow the system setting. */',
    `export type ThemeName = ${themeNames.map((n) => `'${n}'`).join(' | ')};`,
    '',
    '/** The colour roles every theme defines, as #RRGGBB. */',
    'export interface ColorRoles {',
  ];
  for (const role of roles) {
    if (descriptions[role]) lines.push(`  /** ${descriptions[role]}. */`);
    lines.push(`  readonly ${role}: string;`);
  }
  lines.push('}', '');
  lines.push(
    '/** Colour roles per theme. The dark values are temporary (docs/ARCHITECTURE.md section 13). */',
  );
  lines.push(
    `export const colors = ${tsLiteral(themes, '')} as const satisfies Record<ThemeName, ColorRoles>;`,
  );

  for (const [group, tokens] of byGroup(exportedTokens(dictionary.allTokens))) {
    const tree = {};
    for (const token of tokens) {
      let node = tree;
      for (const segment of token.path.slice(1, -1)) node = node[segment] ??= {};
      node[token.path.at(-1)] = tsLeaf(token);
    }
    lines.push('');
    if (TS_GROUP_DOCS[group]) lines.push(`/** ${TS_GROUP_DOCS[group]} */`);
    lines.push(`export const ${group} = ${tsLiteral(tree, '')} as const;`);
  }
  return lines.join('\n') + '\n';
}

